//! Writes `OUT_DIR/openapi.min.json.deflate` and `OUT_DIR/openapi_len.rs`:
//! `docs/openapi.json` with all insignificant whitespace removed, then
//! deflated, and the length of the compact text. `docs/openapi.json` stays
//! pretty-printed because it is the reviewed artifact; the binary embeds the
//! deflated compact form and inflates it per request (see
//! `src/api/openapi.rs`), which saves most of the document's size.

use std::error::Error;
use std::path::PathBuf;

use miniz_oxide::deflate::compress_to_vec;
use miniz_oxide::inflate::decompress_to_vec_with_limit;

/// miniz level 10, the smallest output it makes. Build time is not a concern.
const LEVEL: u8 = 10;

fn main() -> Result<(), Box<dyn Error>> {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let source = manifest.join("../../docs/openapi.json");
    let out = PathBuf::from(std::env::var("OUT_DIR")?);
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", source.display());
    let value: serde_json::Value = serde_json::from_slice(&std::fs::read(&source)?)?;
    let compact = serde_json::to_vec(&value)?;
    let packed = compress_to_vec(&compact, LEVEL);
    if decompress_to_vec_with_limit(&packed, compact.len())
        .as_ref()
        .ok()
        != Some(&compact)
    {
        return Err("docs/openapi.json does not survive compression".into());
    }
    std::fs::write(out.join("openapi.min.json.deflate"), packed)?;
    std::fs::write(
        out.join("openapi_len.rs"),
        format!(
            "/// Bytes of the compact document. Generated by `build.rs`.\nconst DOCUMENT_LEN: usize = {};\n",
            compact.len()
        ),
    )?;
    Ok(())
}
